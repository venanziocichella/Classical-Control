"""Build the browser demos: python3 Web/tools/make_pages.py

Writes Web/routh-hurwitz/*.html, Web/root-locus/*.html,
Web/frequency-response/*.html and Web/index.html from the page definitions in
pages_control.py and pages_fr.py. The pages load ../engine.js (or ../fr.js)
and ../sim.css, so the Web folder works as is from a double-click or on a web
server (GitHub Pages).
"""
import html
import pathlib
import urllib.parse

from pages_control import PAGES
from pages_fr import FR_PAGES

WEB = pathlib.Path(__file__).resolve().parent.parent
REPO = WEB.parent
GITHUB = 'https://github.com/venanziocichella/Classical-Control/blob/main/'

SHELL = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>{title}</title>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Atkinson+Hyperlegible:wght@400;700&family=JetBrains+Mono:wght@400;500&display=swap">
<link rel="stylesheet" href="../sim.css">
</head>
<body>
<!-- Generated by Web/tools/make_pages.py from {source}. MATLAB version: {matlab} -->
<header class="cs-head">
  <a class="cs-back" href="../index.html">All demos</a>
  <h1>{h1}</h1>
  <p>{lead}</p>
</header>
<div id="app"></div>
{scripts}
<script>{pre}
{js}</script>
</body>
</html>
"""

CHAPTERS = [
    ('routh-hurwitz', 'Routh Hurwitz', 'c0_rh'),
    ('root-locus', 'Root Locus', 'c0_rl'),
]
FOLDER = {   # repo folder of each example
    'dc-motor': 'DC Motor', 'car-steering': 'Car Steering', 'cold-storage': 'Cold Storage',
    'inverted-pendulum': 'Inverted Pendulum', 'mass-spring-damper': 'Mass Spring Damper',
    'pendulum': 'Pendulum', 'satellite': 'Satellite', 'two-mass': 'Two Mass System',
    'water-tank': 'Water Tank', 'ball-on-plate': 'Ball on Plate', 'highwire-artist': 'Highwire Artist',
    'cart-pendulum': 'Inverted Pendulum on Cart',
}


def tags(files):
    return '\n'.join(f'<script src="../{f}"></script>' for f in files)


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def main():
    for folder, chapter, key in CHAPTERS:
        for name, p in PAGES.items():
            pre = ''
            if 'DEFAULT_C' in p['js']:
                pre = f"\nconst DEFAULT_C = '{p[key]}';   // default C(s) of the {chapter} example"
            write(WEB / folder / f'{name}.html', SHELL.format(
                title=p['title'], h1=html.escape(p['h1']), lead=html.escape(p['lead']) + ' Type a controller C(s) and press Apply.',
                source='pages_control.py', matlab=f"{chapter}/{FOLDER[name]}/{p['matlab']}",
                scripts=tags(['engine.js']), pre=pre, js=p['js']))
    for name, p in FR_PAGES.items():
        write(WEB / 'frequency-response' / f'{name}.html', SHELL.format(
            title=p['title'], h1=html.escape(p['h1']), lead=html.escape(p['lead']),
            source='pages_fr.py', matlab=p['matlab'], scripts=tags(p.get('scripts', ['engine.js', 'fr.js'])), pre='', js=p['js']))
    write(WEB / 'index.html', index())
    write(REPO / 'index.html', home())


def index():
    def cards(folder, items):
        return '\n'.join(
            f'      <li><a href="{folder}/{name}.html"><span class="ix-name">{html.escape(p["title"])}</span>'
            f'<span class="ix-lead">{html.escape(p["lead"])}</span></a></li>' for name, p in items)
    groups = [
        ('routh-hurwitz', 'Routh Hurwitz', 'Same sims as the MATLAB Realtime demos: type C(s), watch the closed loop, read the closed-loop poles.', PAGES.items()),
        ('root-locus', 'Root Locus', 'The same sims with the Root Locus default controllers.', PAGES.items()),
        ('frequency-response', 'Frequency Response', 'Chapter 7 demos: what a linear system does to a sinusoid, and a song played through G(s).', FR_PAGES.items()),
    ]
    body = '\n'.join(
        f'  <section class="ix-group">\n    <h2>{t}</h2>\n    <p>{html.escape(d)}</p>\n    <ul class="ix-list">\n{cards(f, it)}\n    </ul>\n  </section>'
        for f, t, d, it in groups)
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>ME3600 Control Demos</title>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Atkinson+Hyperlegible:wght@400;700&family=JetBrains+Mono:wght@400;500&display=swap">
<link rel="stylesheet" href="sim.css">
</head>
<body>
<!-- Generated by Web/tools/make_pages.py -->
<header class="cs-head ix-head">
  <a class="cs-back" href="../index.html">Course home</a>
  <h1>ME3600 control demos</h1>
  <p>Real-time simulations from the course. No MATLAB needed: pick an example, type your controller C(s) and test it.</p>
</header>
<main class="ix-main">
{body}
</main>
</body>
</html>
"""


# Course home (repo root index.html): every chapter folder with its MATLAB files,
# and a link to the browser version of each example that has one.
HOME_CHAPTERS = [   # (repo folder, browser demo folder)
    ('Routh Hurwitz', 'routh-hurwitz'), ('Root Locus', 'root-locus'),
    ('Frequency Response', 'frequency-response'), ('Bode Plots', None),
]
HIDE = {   # files kept in the repo but not listed on the course home
    'Root Locus/Mass Spring Damper/MSD_sim.slx', 'Root Locus/Mass Spring Damper/MSD_Control_Design.pdf',
    'Root Locus/Inverted Pendulum/IP_Control_Design.pdf',
}
FR_FOLDER = {'Servo (First Order)': 'servo', 'Spring Damper (High Pass)': 'spring-damper',
             'Mass Spring Damper (Second Order)': 'mass-spring-damper', 'Muffled Song': 'muffled-song'}


def home():
    slug = {v: k for k, v in FOLDER.items()} | FR_FOLDER
    url = lambda path: urllib.parse.quote(path.relative_to(REPO).as_posix())

    def files(folder):
        out = []
        for f in sorted(p for p in folder.iterdir() if p.is_file() and not p.name.startswith('.')):
            rel = f.relative_to(REPO).as_posix()
            if rel in HIDE or (f.name == 'README.md' and rel.startswith('Frequency Response/')):
                continue
            href = GITHUB + url(f) if f.suffix == '.md' else url(f)
            out.append(f'<li><a href="{href}">{html.escape(f.name)}</a></li>')
        return '<ul class="hm-files">' + ''.join(out) + '</ul>' if out else ''

    def card(folder, demo):
        name = slug.get(folder.name)
        p = (FR_PAGES if demo == 'frequency-response' else PAGES).get(name) if name else None
        run = f'<a class="cs-btn cs-primary" href="Web/{demo}/{name}.html">Run in the browser</a>' if p and demo else ''
        lead = f'<p class="ix-lead">{html.escape(p["lead"])}</p>' if p else ''
        return f'      <li class="hm-card"><h3>{html.escape(folder.name)}</h3>{lead}{run}{files(folder)}</li>'

    sections = []
    for folder, demo in HOME_CHAPTERS:
        d = REPO / folder
        subs = sorted(p for p in d.iterdir() if p.is_dir() and not p.name.startswith('.'))
        top = files(d)
        sections.append(f'  <section class="ix-group">\n    <h2>{folder}</h2>\n'
                        + (f'    {top}\n' if top else '')
                        + (f'    <ul class="ix-list">\n' + '\n'.join(card(p, demo) for p in subs) + '\n    </ul>\n' if subs else '')
                        + '  </section>')
    body = '\n'.join(sections)
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>ME3600 Classical Control</title>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Atkinson+Hyperlegible:wght@400;700&family=JetBrains+Mono:wght@400;500&display=swap">
<link rel="stylesheet" href="Web/sim.css">
</head>
<body>
<!-- Generated by Web/tools/make_pages.py -->
<header class="cs-head ix-head">
  <h1>ME3600 Classical Control</h1>
  <p>MATLAB examples and demos of the course, by chapter. Click a file to download it, or run the demo in the browser (no MATLAB needed): <a href="Web/index.html">all browser demos</a>.</p>
</header>
<main class="ix-main">
{body}
</main>
</body>
</html>
"""


if __name__ == '__main__':
    main()
